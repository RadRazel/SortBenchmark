// Здесь собраны наши собственные сортировки.
// Сравниваем строки "по буквам" (лексикографически) через string.CompareOrdinal:
//   результат < 0  — первая строка меньше (должна стоять раньше),
//   результат = 0  — строки равны,
//   результат > 0  — первая строка больше.
// Ordinal значит "сравнить коды символов" — для строчных латинских букв
// это обычный алфавитный порядок, и так быстрее всего.

static class Sorts
{
    // ===================== 1. СОРТИРОВКА СЛИЯНИЕМ =====================
    // Идея: делим массив пополам, сортируем каждую половину (рекурсивно),
    // а потом СЛИВАЕМ две отсортированные половины в одну.
    // Сложность: O(N * log N) — очень быстро даже для огромных N.

    public static void MergeSort(string[] a)
    {
        // Вспомогательный массив того же размера — в него сливаем половинки.
        // Создаём его один раз, чтобы не тратить время на новые массивы в рекурсии.
        string[] buffer = new string[a.Length];
        MergeSortRange(a, buffer, 0, a.Length);
    }

    // Сортирует часть массива a с индекса left (включительно) до right (НЕ включительно).
    static void MergeSortRange(string[] a, string[] buffer, int left, int right)
    {
        // Если в куске 0 или 1 элемент — он уже отсортирован.
        if (right - left <= 1)
            return;

        int middle = left + (right - left) / 2;

        MergeSortRange(a, buffer, left, middle);   // сортируем левую половину
        MergeSortRange(a, buffer, middle, right);  // сортируем правую половину

        // Сливаем: берём по очереди меньший из "первых" элементов двух половин.
        int i = left;    // указатель в левой половине
        int j = middle;  // указатель в правой половине
        int k = left;    // куда кладём в buffer

        while (i < middle && j < right)
        {
            // "<= 0" — при равенстве берём из левой половины (сортировка устойчивая)
            if (string.CompareOrdinal(a[i], a[j]) <= 0)
                buffer[k++] = a[i++];
            else
                buffer[k++] = a[j++];
        }

        // Одна из половин закончилась — дописываем остаток другой.
        while (i < middle) buffer[k++] = a[i++];
        while (j < right) buffer[k++] = a[j++];

        // Копируем слитый результат обратно в a.
        for (int t = left; t < right; t++)
            a[t] = buffer[t];
    }

    // ===================== 2. СОРТИРОВКА ВСТАВКАМИ =====================
    // Идея: как сортируют карты в руке. Идём слева направо, берём очередной
    // элемент и сдвигаем его влево, пока слева не окажется элемент меньше или равный.
    // Сложность: O(N^2) — для больших N ОЧЕНЬ медленно
    // (N = 10^5 → ~2.5 * 10^9 сравнений, N = 10^8 → ~2.5 * 10^15, это годы!).
    // Зато на маленьких массивах она быстрая: простой код, никакой рекурсии.

    public static void InsertionSort(string[] a)
    {
        for (int i = 1; i < a.Length; i++)
        {
            string current = a[i];   // элемент, который вставляем
            int j = i - 1;

            // Сдвигаем вправо все элементы, которые больше current.
            while (j >= 0 && string.CompareOrdinal(a[j], current) > 0)
            {
                a[j + 1] = a[j];
                j--;
            }

            a[j + 1] = current;      // ставим current на освободившееся место
        }
    }

    // ===================== Проверка результата =====================

    // Возвращает true, если каждый элемент не больше следующего.
    public static bool IsSorted(string[] a)
    {
        for (int i = 1; i < a.Length; i++)
        {
            if (string.CompareOrdinal(a[i - 1], a[i]) > 0)
                return false;
        }
        return true;
    }

    // Возвращает true, если два массива совпадают поэлементно.
    public static bool SameArrays(string[] x, string[] y)
    {
        if (x.Length != y.Length)
            return false;
        for (int i = 0; i < x.Length; i++)
        {
            if (x[i] != y[i])
                return false;
        }
        return true;
    }
}
